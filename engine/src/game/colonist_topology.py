def get_edge_corners(edge_id: int) -> Tuple[int, int]:
    """Get the two corners connected by an edge."""
    if edge_id not in EDGE_CORNERS:
        raise ValueError(f"Invalid edge_id: {edge_id}")
    return EDGE_CORNERS[edge_id]


def get_corner_edges(corner_id: int) -> List[int]:
    """Get all edges connected to a corner."""
    if corner_id not in CORNER_EDGES:
        raise ValueError(f"Invalid corner_id: {corner_id}")
    return CORNER_EDGES[corner_id]


def get_corner_neighbors(corner_id: int) -> List[int]:
    """Get all corners adjacent to a corner (for distance rule)."""
    if corner_id not in CORNER_NEIGHBORS:
        raise ValueError(f"Invalid corner_id: {corner_id}")
    return CORNER_NEIGHBORS[corner_id]


def are_corners_adjacent(c1: int, c2: int) -> bool:
    """Check if two corners are adjacent (connected by an edge)."""
    return c2 in CORNER_NEIGHBORS.get(c1, [])


def get_edge_between_corners(c1: int, c2: int) -> int:
    """Get the edge connecting two adjacent corners, or -1 if not adjacent."""
    for edge_id, (ec1, ec2) in EDGE_CORNERS.items():
        if (c1, c2) == (ec1, ec2) or (c2, c1) == (ec1, ec2):
            return edge_id
    return -1


def is_valid_settlement_location(corner_id: int, occupied_corners: Set[int]) -> bool:
    """
    Check if a corner is valid for settlement placement.

    A corner is valid if:
    1. It's not already occupied
    2. No adjacent corners are occupied (distance rule)
    """
    if corner_id < 0 or corner_id >= NUM_CORNERS:
        return False

    if corner_id in occupied_corners:
        return False

    neighbors = CORNER_NEIGHBORS.get(corner_id, [])
    for neighbor in neighbors:
        if neighbor in occupied_corners:
            return False

    return True


def is_valid_road_location(
    edge_id: int,
    player_corners: Set[int],
    player_edges: Set[int],
    all_occupied_edges: Set[int]
) -> bool:
    """
    Check if an edge is valid for road placement.

    A road is valid if:
    1. The edge is not already occupied
    2. The edge connects to a player's settlement/city OR existing road
    """
    if edge_id < 0 or edge_id >= NUM_EDGES:
        return False

    if edge_id in all_occupied_edges:
        return False

    c1, c2 = EDGE_CORNERS[edge_id]

    # Check if connects to player's building
    if c1 in player_corners or c2 in player_corners:
        return True

    # Check if connects to player's existing road
    for other_edge in player_edges:
        oc1, oc2 = EDGE_CORNERS[other_edge]
        if c1 in (oc1, oc2) or c2 in (oc1, oc2):
            return True

    return False


def is_valid_setup_road_location(
    edge_id: int,
    settlement_corner: int,
    all_occupied_edges: Set[int]
) -> bool:
    """
    Check if an edge is valid for setup road placement.

    During setup, the road must connect to the just-placed settlement.
    """
    if edge_id < 0 or edge_id >= NUM_EDGES:
        return False

    if edge_id in all_occupied_edges:
        return False

    c1, c2 = EDGE_CORNERS[edge_id]
    return settlement_corner in (c1, c2)


# Build adjacency matrices for GNN
def build_corner_adjacency_matrix():
    """Build 54x54 adjacency matrix for corners."""
    import numpy as np
    adj = np.zeros((NUM_CORNERS, NUM_CORNERS), dtype=np.float32)
    for c1, neighbors in CORNER_NEIGHBORS.items():
        for c2 in neighbors:
            adj[c1, c2] = 1.0
            adj[c2, c1] = 1.0
    return adj


def build_edge_adjacency_matrix():
    """Build 72x72 adjacency matrix for edges (edges sharing a corner)."""
    import numpy as np
    adj = np.zeros((NUM_EDGES, NUM_EDGES), dtype=np.float32)
    for e1 in range(NUM_EDGES):
        c1, c2 = EDGE_CORNERS[e1]
        # Find all edges that share corner c1 or c2
        for e2 in CORNER_EDGES[c1]:
            if e1 != e2:
                adj[e1, e2] = 1.0
                adj[e2, e1] = 1.0
        for e2 in CORNER_EDGES[c2]:
            if e1 != e2:
                adj[e1, e2] = 1.0
                adj[e2, e1] = 1.0
    return adj


